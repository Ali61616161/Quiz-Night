const TR_LETTERS = /[çğıöşüÇĞİÖŞÜ]/;
const TR_WORDS = /(?<![\p{L}])(ile|Müzesi|Nehri|Gölü|Adası|Milli|Parkı|ilçesi|Sarayı|Kulesi)(?![\p{L}])/u;
const TR_FN = /(?<![\p{L}])(hangi|hangisi|kaç|nedir|kimdir|kimdir|için|olan|olarak|değil|adlı|nedeniyle|aşağıdaki|hangisidir)(?![\p{L}])/iu;
/** Çevirisiz kalmış Türkçe işareti: işlev sözcükleri (özel adlardaki aksanlı harfler sorun sayılmaz). */
export const leaksTr = (s: string) => {
  const t = s.replace(/[“"][^”"]*[”"]/g, " ").replace(/\([^)]*\)/g, " "); // tırnaktaki eser adları ve parantez içi özgün adlar sayılmaz
  return TR_WORDS.test(t) || TR_FN.test(t);
};
export const hasTurkish = (s: string) => TR_LETTERS.test(s) || TR_WORDS.test(s);

const ORD = (n: number) => { const s = ["th", "st", "nd", "rd"], v = n % 100; return n + (s[(v - 20) % 10] || s[v] || s[0]); };
export { ORD };

/** Tek bir alanı İngilizceye çevirir; güvenilir çeviri yoksa null (satır atlanır). */
export function toEn(field: string): string | null {
  const parts = field.split(";").map((p) => p.trim());
  const out: string[] = [];
  for (let p of parts) {
    // "A (B)" biçimi: B yalnızca ASCII ise (İngilizce özgün ad) onu, değilse A'yı kullan
    const m = p.match(/^(.*?)\s*\(([^)]*)\)\s*$/);
    if (m) p = m[2] && !leaksTr(m[2]) && /^[\x20-\x7E]+$/.test(m[2]) && /[A-Za-z]{3}/.test(m[2]) && m[1] !== m[2] && leaksTr(m[1]) ? m[2] : m[1];
    const mapped = DICT.get(p) ?? p;
    if (leaksTr(mapped)) { if (out.length === 0 && parts.indexOf(p) === 0) return null; continue; }
    out.push(mapped);
  }
  return out.length ? out.join(";") : null;
}

